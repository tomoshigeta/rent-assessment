/**
 * Ver1 が置いている仮定。すべてここに集める。
 *
 * このファイルの値は「実務感覚で置いた仮値」であり、観測された事実ではない。
 * 誰がなぜ決めたか、実データとどう違うかは docs/spec.md 第2章に書いてある。
 * 値を変えると r の幅が動くので、変えるときは spec の該当箇所も直すこと。
 */

/**
 * 比較期間（月）。
 *
 * 【仮定】Ver1 では 24ヶ月に固定する。利用者は変更できない。
 * 【根拠】実際の募集図面6件すべてが契約期間2年だった。
 * 【影響】H を伸ばすと借主上限と貸主下限の幅が狭まり、ある点で交差する。
 *        交差点は H = (査定×空室 + 原状回復 + 転居費用) / (査定 − 現在賃料)。
 *        検証データでは92ヶ月付近。24ヶ月では十分な余裕がある。
 */
export const HORIZON_MONTHS = 24

/**
 * 更新料の月数（新賃料に対する倍率）。
 *
 * 【仮定】新賃料の 1.25ヶ月分。
 * 【根拠】利用者の実務感覚による指定。
 * 【実データとの差】募集図面6件のうち5件は「更新料 新賃料1ヶ月」、1件は記載なし。
 *        つまり実データより 0.25ヶ月分だけ高く見積もっている。
 * 【影響】借主上限・貸主下限の分母 (H + この値) に入る。
 *        1.0 にすると両方の上限・下限がそれぞれ約1%上がる。
 */
export const RENEWAL_FEE_MONTHS = 1.25

/**
 * 転居費用の月数（現在賃料に対する倍率）。
 *
 * 【仮定】現在賃料の 5ヶ月分。礼金・仲介手数料・保証料・鍵交換・保険・引越代の総額を
 *        1つの数字にまとめたもの。
 * 【根拠】利用者の実務感覚による指定。Ver1 ではパラメータを最小限にするため
 *        費目別の入力を持たない。
 * 【実データとの差】募集図面6件から積み上げると 2.5〜3.7ヶ月分相当だった
 *        （礼金の中央値1ヶ月、鍵交換27,500円、保険22,000円、保証料0.4〜0.5ヶ月、
 *        仲介手数料は6件中2件のみ1ヶ月、引越代は図面に載らない）。
 *        つまり実データより 1.3〜2.5ヶ月分だけ多く見積もっている。
 * 【影響】借主上限を直接動かす。この値をxとすると上限 = 現在賃料×(H+x)/(H+RENEWAL_FEE_MONTHS)。
 *        3.7ヶ月にすると上限が現在賃料の1.0396倍まで下がる（5ヶ月では1.1485倍）。
 */
export const MOVING_COST_MONTHS = 5

/** 空室期間として選べる月数。Ver1 は1〜3のいずれか。 */
export const VACANCY_MONTH_CHOICES = [1, 2, 3] as const
export type VacancyMonths = (typeof VACANCY_MONTH_CHOICES)[number]

/**
 * 「相場並み」とみなす乖離率の幅（±%）。
 *
 * 【仮定】±2.5%。
 * 【根拠】利用者の実務感覚による仮値。根拠となるデータはまだない。
 * 【影響】r 軸に重ねて表示する帯の幅。計算結果そのものには影響しない。
 */
export const FAIR_BAND_PCT = 2.5

/**
 * 強い警告を出す乖離率（±%）。
 *
 * 【仮定】±20%。
 * 【根拠】利用者の実務感覚による仮値。
 * 【影響】表示のみ。
 */
export const STRONG_WARNING_PCT = 20

/**
 * 査定賃料を自動算出するために必要な比較事例の最低件数。
 *
 * 【仮定】5件。
 * 【根拠】実際の募集図面を集めたところ、同一エリア・同一条件で同時期に集まったのが6件だった。
 *        当初8件としていたが、6件では判定不能になるため5件へ引き下げた。
 * 【例外】査定賃料を手入力で上書きした場合、この件数チェックは適用しない。
 *        比較事例は資料掲載用となり、計算には使われないため。
 */
export const MIN_SAMPLE_COUNT = 5

/**
 * 借主上限の係数。上限 = 現在賃料 × この値。
 *
 * (H + 転居費用月数) / (H + 更新料月数) = (24 + 5) / (24 + 1.25) = 1.14851…
 *
 * 査定賃料に依存しないのが Ver1 の重要な性質。
 * 「更新後賃料が現在賃料の約14.9%増を超えると、借主は転居したほうが得になる」と読める。
 */
export const TENANT_CEILING_FACTOR =
  (HORIZON_MONTHS + MOVING_COST_MONTHS) / (HORIZON_MONTHS + RENEWAL_FEE_MONTHS)
